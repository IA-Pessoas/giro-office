function confirmed({
  sourceTable,
  legacyModule,
  legacyReferences,
  operations,
  relationships,
  current,
  reason,
}) {
  return decision({
    sourceTable,
    legacyModule,
    legacyReferences,
    operations,
    legacyRelationships: relationships,
    currentContractEvidence: current,
    finalStatus: "confirmed",
    reasonCode: "LEGACY_BEHAVIOR_CONFIRMED",
    reason,
    confidence: "high",
    ruleId: `admin-business:${sourceTable}`,
  });
}

function pending({
  sourceTable,
  legacyModule,
  legacyReferences,
  operations,
  relationships,
  current = [],
  reasonCode = "NO_CURRENT_CONTRACT",
  reason,
}) {
  return decision({
    sourceTable,
    legacyModule,
    legacyReferences,
    operations,
    legacyRelationships: relationships,
    currentContractEvidence: current,
    finalStatus: "pending",
    reasonCode,
    reason,
    confidence: "low",
    ruleId: null,
  });
}

function decision(value) {
  return Object.freeze({
    ...value,
    legacyReferences: Object.freeze(value.legacyReferences),
    operations: Object.freeze(value.operations),
    legacyRelationships: Object.freeze(value.legacyRelationships),
    currentContractEvidence: Object.freeze(value.currentContractEvidence),
  });
}

